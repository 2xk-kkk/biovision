def main():
    db = connect_db()
    total_added = 0
    
    for textbook_name, chapters in textbooks.items():
        exam_id = add_exam_if_not_exists(db, textbook_name)
        question_number = 1
        
        for chapter_name, sections in chapters.items():
            for section_name, question_data_list in sections.items():
                for q_data in question_data_list:
                    template_index, topic, correct, wrong1, wrong2, wrong3 = q_data
                    question = generate_question(template_index, topic, correct, wrong1, wrong2, wrong3)
                    
                    add_question(
                        db, exam_id, question_number,
                        question['stem'],
                        question['options'][0],
                        question['options'][1],
                        question['options'][2],
                        question['options'][3],
                        question['answer'],
                        textbook_name,
                        chapter_name,
                        section_name
                    )
                    question_number += 1
                    total_added += 1
                    if total_added % 100 == 0:
                        print(f'已添加 {total_added} 道题目...')
    
    db.close()
    print(f'\n题目生成完成！共添加 {total_added} 道题目。')

if __name__ == '__main__':
    main()