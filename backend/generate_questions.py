import sqlite3
import json
import random

def connect_db():
    return sqlite3.connect('forum.db')

def add_exam_if_not_exists(db, name):
    cursor = db.cursor()
    cursor.execute('SELECT id FROM exams WHERE name = ?', (name,))
    result = cursor.fetchone()
    if result:
        return result[0]
    cursor.execute('INSERT INTO exams (name, file_name, question_count) VALUES (?, ?, ?)', 
                   (name, '', 0))
    db.commit()
    return cursor.lastrowid

def add_question(db, exam_id, number, stem, option_a, option_b, option_c, option_d, answer, textbook, chapter, section):
    cursor = db.cursor()
    try:
        images_json = json.dumps([])
        cursor.execute('''
            INSERT OR IGNORE INTO questions 
            (exam_id, number, stem, option_a, option_b, option_c, option_d, answer, images, textbook, chapter, section)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        ''', (exam_id, number, stem, option_a, option_b, option_c, option_d, answer, images_json, textbook, chapter, section))
        db.commit()
        return cursor.lastrowid
    except Exception as e:
        db.rollback()
        print(f'添加题目失败: {e}')
        return None

